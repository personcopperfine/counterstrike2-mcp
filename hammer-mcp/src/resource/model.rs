//! Compiled-model facts: what a map author needs to place a prop, read out of a `*.vmdl_c`.
//!
//! [`model_info_from_bytes`] takes the bytes of one compiled model (the container is parsed by
//! [`crate::resource`], the blocks by [`crate::kv3bin`]) and returns a [`ModelInfo`]. It reads:
//!
//! | field | source |
//! |---|---|
//! | `name` | `DATA.m_name` (the engine name, `…​.vmdl`) |
//! | `hull` / `view` | `DATA.m_modelInfo.m_vHullMin/Max` and `m_vViewMin/Max` |
//! | `mass` | `DATA.m_modelInfo.m_flMass` |
//! | `surface_property` | `DATA.m_modelInfo.m_sSurfaceProperty` |
//! | `keyvalues_text` | `DATA.m_modelInfo.m_keyValueText` (embedded KV3 text: `prop_data`, …) |
//! | `skins` | `DATA.m_materialGroups[].m_name` (the values the `skin` keyvalue selects) |
//! | `bodygroups` | `DATA.m_meshGroups[]` + `DATA.m_refMeshGroupMasks[]` |
//! | `sequences` | `ASEQ.m_localSequenceNameArray[]` (else `m_localS1SeqDescArray[].m_sName`) |
//! | `attachments` | `MDAT.m_attachments[].value.m_name` |
//! | `has_physics` | a `PHYS` block, or a non-empty `DATA.m_refPhysicsData` |
//! | `render_bounds` | union of `MDAT.m_sceneObjects[].m_vMinBounds`/`m_vMaxBounds` |
//! | `physics_bounds` | union of `PHYS.m_parts[].m_rnShape` hull/mesh/sphere/capsule boxes |
//!
//! # Verified against real content
//!
//! Measured by decoding **every** KV3 block of all 13 105 `*.vmdl_c` of the installed
//! `game/csgo/pak01_dir.vpk` (66 334 blocks, 10 189 of them with binary blobs) — the `#[ignore]`d
//! `corpus_models_decode` test of `tests/resource.rs` does exactly that:
//!
//! * `DATA.m_modelInfo.m_vHullMin/Max` is **all zero in 13 024 of 13 105** models; the 81 that
//!   carry a real box are the player/agent models (`[-16,-16,0]..[16,16,72]`). The usable boxes
//!   come from `MDAT` (`m_sceneObjects[].m_vMinBounds/m_vMaxBounds`, present in all but 9 models)
//!   and `PHYS`, which is why [`ModelInfo::render_bounds`] and [`ModelInfo::physics_bounds`] exist
//!   next to the `m_modelInfo` values the brief asked for.
//! * `m_flMass` is 0 in all 13 105 (also in `PHYS.m_parts[].m_flMass`): the engine derives mass
//!   from the collision shape and the surface property, so `mass` is `None` in the whole corpus.
//! * `m_sSurfaceProperty` is present but **empty in all 13 105**: the property is authored on the
//!   `.vmdl`, not kept in the compiled model, so `surface_property` is `None` there too.
//! * `m_keyValueText` (the model's keyvalues as KV3 *text*: `prop_data`, …) is non-empty in 1 333
//!   models. It is a `<!-- kv3 encoding:text:…` document, not a plain `keyvalues` blob.
//! * `m_materialGroups` (the `skin` choices) is non-empty in 3 994 models (up to 14 per model),
//!   `m_meshGroups` (bodygroups) in 183 (up to 64 — more groups than a 64-bit `bodygroups` keyvalue
//!   can select); those names are either authored (`first_or_third_person_@0_#&thirdperson_default`)
//!   or auto-generated by Valve's exporter (`bg_@0`), and [`BodyGroup::group`]/[`BodyGroup::choice`]
//!   split the authored form. `ASEQ` sequences are present in 941 models (up to 42), `MDAT`
//!   attachments in 624 (up to 17).
//! * `m_refPhysicsData` is empty in all 13 105; `has_physics` follows the `PHYS` block, which
//!   9 926 models carry (9 822 of those have a hull/mesh/sphere box; the rest are capsule-only).
//! * `MDAT` may occur several times (an agent model has five), so bounds and attachments are
//!   unioned/collected over every block of their type. A secondary block that fails to decode is
//!   reported in [`ModelInfo::notes`] (its facts are missing), never silently dropped; the `DATA`
//!   block — the one that carries the model — is a hard error.

use super::kv3bin::{self, Kv3Value};
use super::{BlockRef, Resource, ResourceError};

/// An axis-aligned box as `(min, max)`.
pub type Aabb = ([f32; 3], [f32; 3]);

/// One attachment with the placement data its first influence carries (`m_influenceNames[0]`,
/// `m_vInfluenceOffsets[0]`). The offset is relative to that bone, so two attachments are only
/// comparable when `bone` is equal; `None` offset = the file had none for it.
#[derive(Debug, Clone, PartialEq)]
pub struct AttachmentPoint {
    pub name: String,
    pub bone: Option<String>,
    pub offset: Option<[f32; 3]>,
    /// `m_nInfluences`: the offset is a model-frame candidate only when this is 1.
    pub influences: Option<u32>,
    /// `m_bInfluenceRootTransform[0]` (the offset is then not bone-relative at all).
    pub root_transform: bool,
    /// Whether the bone's frame equals the model frame: the bone and every parent up to the root
    /// have identity rest rotation and unit scale (`DATA.m_modelSkeleton`). `None` = the file has
    /// no skeleton entry for the bone, so nothing is known.
    pub bone_aligned: Option<bool>,
}

impl AttachmentPoint {
    /// The offset read as a model-space position, or why it cannot be (the facing decision uses
    /// only these).
    pub fn model_offset(&self) -> Result<[f32; 3], String> {
        let offset = self.offset.ok_or_else(|| format!("{} has no offset", self.name))?;
        if self.influences != Some(1) {
            return Err(format!(
                "{} has {} influences (the offset is only a position for exactly one)",
                self.name,
                self.influences.map_or("an unknown number of".to_string(), |n| n.to_string())
            ));
        }
        if self.root_transform {
            return Err(format!("{}'s offset is relative to the root transform, not a bone", self.name));
        }
        match self.bone_aligned {
            Some(true) => Ok(offset),
            Some(false) => Err(format!(
                "{}'s bone {} (or a parent) is rotated or scaled, so its offset is in the bone's frame, not the model's",
                self.name,
                self.bone.as_deref().unwrap_or("?")
            )),
            None => Err(format!("{}'s bone is not in the model skeleton, its frame is unknown", self.name)),
        }
    }
}

/// Does `bone` (by name) and its whole parent chain have identity rest rotation and unit scale?
/// `None` when the skeleton or the bone is missing. `m_boneRotParent` is parent-relative
/// `(x, y, z, w)`; a quaternion and its negative are one rotation, so only `|w|` matters.
fn bone_aligned(root: &Kv3Value, bone: &str) -> Option<bool> {
    let skeleton = root.get("m_modelSkeleton")?;
    let names = skeleton.get("m_boneName")?.as_array()?;
    let parents = skeleton.get("m_nParent")?.as_array()?;
    let rotations = skeleton.get("m_boneRotParent")?.as_array()?;
    let scales = skeleton.get("m_boneScaleParent").and_then(Kv3Value::as_array);
    let mut index = names.iter().position(|n| n.as_str() == Some(bone))?;
    for _ in 0..=names.len() {
        let q = rotations.get(index)?.as_array()?;
        let w = q.get(3)?.as_f64()?;
        if w.abs() < 0.9999 {
            return Some(false);
        }
        if let Some(scale) = scales.and_then(|s| s.get(index)).and_then(Kv3Value::as_f64) {
            if (scale - 1.0).abs() > 0.01 {
                return Some(false);
            }
        }
        let parent = parents.get(index)?.as_i64()?;
        if parent < 0 {
            return Some(true);
        }
        index = parent as usize;
    }
    None // a parent loop: the file is not trustworthy
}

/// One bodygroup: CS2 stores these as a *named mesh group* list plus one 64-bit mask per mesh. An
/// entity's `bodygroups` keyvalue is the bit mask of the groups to switch on, so a group's "choice"
/// is its bit ([`BodyGroup::value`]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BodyGroup {
    /// Bit index in `DATA.m_refMeshGroupMasks` (and in the entity's bodygroups mask).
    pub index: u32,
    /// `DATA.m_meshGroups[index]`, e.g. `bg_@0` or `first_or_third_person_@2_#&firstperson_default`.
    pub name: String,
    /// The mask bit that selects this group (`1 << index`).
    pub value: u64,
    /// How many `DATA.m_refMeshGroupMasks` entries have this bit set (the meshes in this group).
    pub mesh_count: usize,
    /// The bodygroup name parsed out of `name` when it carries the exporter's `_@` marker —
    /// the authored `"<group>_@<choice index>_#&<choice name>"` spells both, and the
    /// auto-generated `"bg_@<choice index>"` still yields the group (`"bg"`) with no choice.
    /// `None` only when the name has no marker at all (a plain label).
    pub group: Option<String>,
    /// The choice name parsed out of `name` (see [`BodyGroup::group`]).
    pub choice: Option<String>,
}

/// The facts a map author needs about one compiled model.
#[derive(Debug, Clone, PartialEq)]
pub struct ModelInfo {
    /// `DATA.m_name`, e.g. `models/props/de_dust/hr_dust/x.vmdl`.
    pub name: Option<String>,
    /// `DATA.m_modelInfo.m_vHullMin/Max` — only when the file carries a real (non-zero) box.
    pub hull: Option<Aabb>,
    /// `DATA.m_modelInfo.m_vViewMin/Max` — only when the file carries a real (non-zero) box.
    pub view: Option<Aabb>,
    /// `DATA.m_modelInfo.m_flMass` — only when it is not 0.
    pub mass: Option<f32>,
    /// `DATA.m_modelInfo.m_sSurfaceProperty` (drives physics material/density).
    pub surface_property: Option<String>,
    /// `DATA.m_modelInfo.m_keyValueText`: the model's keyvalues as KV3 text (`prop_data`, …).
    pub keyvalues_text: Option<String>,
    /// The `skin` choices: `DATA.m_materialGroups[].m_name` in file order.
    pub skins: Vec<String>,
    /// The bodygroups (`DATA.m_meshGroups` with the per-mesh masks).
    pub bodygroups: Vec<BodyGroup>,
    /// Embedded sequence names from the `ASEQ` block.
    pub sequences: Vec<String>,
    /// Attachment point names from the `MDAT` blocks.
    pub attachments: Vec<String>,
    /// The same attachments with the first influence's bone and offset (bone-relative, not model
    /// space) when the file carries them: what `facing` compares.
    pub attachment_points: Vec<AttachmentPoint>,
    /// Whether the model carries collision: a `PHYS` block or non-empty `m_refPhysicsData`.
    pub has_physics: Option<bool>,
    /// The union of the render meshes' bounds (`MDAT.m_sceneObjects[]`), the box to draw/wrap.
    pub render_bounds: Option<Aabb>,
    /// The union of the physics shapes' boxes (`PHYS.m_parts[].m_rnShape`).
    pub physics_bounds: Option<Aabb>,
    /// `DATA.m_modelSkeleton`: `(bone name, parent index or -1)` in file order; empty for a
    /// model without bones.
    pub bones: Vec<(String, i64)>,
    /// The container's block types, in file order (`DATA`, `MDAT`, `MBUF`, …).
    pub blocks: Vec<String>,
    /// What could not be decoded or is missing, in plain words. Never empty when a field above is
    /// `None`/empty for a reason the file itself shows.
    pub notes: Vec<String>,
}

/// Read the compiled model facts out of `*.vmdl_c` bytes.
pub fn model_info_from_bytes(bytes: &[u8]) -> Result<ModelInfo, ResourceError> {
    let resource = Resource::parse(bytes)?;
    let mut notes = Vec::new();

    let data_blocks: Vec<&BlockRef> = resource.blocks_of(b"DATA").collect();
    let Some(&first) = data_blocks.first() else {
        return Err(ResourceError::MissingBlock {
            kind: "DATA",
            blocks: resource.block_types().join(", "),
        });
    };
    if data_blocks.len() > 1 {
        notes.push(format!(
            "{} DATA blocks: only the first is read",
            data_blocks.len()
        ));
    }
    let document = kv3bin::decode(resource.block_bytes(first))?;
    let root = &document.root;
    if root.as_object().is_none() {
        return Err(ResourceError::UnexpectedValue {
            what: "the DATA root",
            expected: "an object",
            found: root.kind_name(),
        });
    }

    let info = root.get("m_modelInfo");
    let hull = info.and_then(|info| box_pair(info, "m_vHullMin", "m_vHullMax"));
    let view = info.and_then(|info| box_pair(info, "m_vViewMin", "m_vViewMax"));
    let mass = info
        .and_then(|info| info.get("m_flMass"))
        .and_then(Kv3Value::as_f32)
        .filter(|value| *value != 0.0);
    let surface_property = info
        .and_then(|info| info.get_str("m_sSurfaceProperty"))
        .filter(|text| !text.is_empty())
        .map(str::to_owned);
    let keyvalues_text = info
        .and_then(|info| info.get_str("m_keyValueText"))
        .filter(|text| !text.is_empty())
        .map(str::to_owned);

    if info.is_none() {
        notes.push("DATA has no m_modelInfo (hull/view/mass/surface property are unknown)".into());
    } else {
        if hull.is_none() && view.is_none() {
            notes.push(
                "m_modelInfo's hull and view boxes are all zero (normal for compiled CS2 models: \
                 the engine derives them) — renderBounds/physicsBounds are the usable boxes"
                    .into(),
            );
        } else if hull.is_none() {
            notes.push("m_modelInfo.m_vHullMin/Max are all zero — use renderBounds".into());
        }
        if mass.is_none() {
            notes.push(
                "m_modelInfo.m_flMass is 0/absent: the engine derives mass from the collision \
                 shape + surface property"
                    .into(),
            );
        }
    }

    let skins = material_group_names(root);
    if skins.is_empty() {
        notes.push(
            "m_materialGroups is empty/unnamed: the model lists its materials on the render meshes \
             (MDAT), so it has no skin choices"
                .into(),
        );
    }

    let (bodygroups, bodygroup_notes) = body_groups(root);
    notes.extend(bodygroup_notes);

    let (sequences, sequence_notes) = sequences(&resource);
    notes.extend(sequence_notes);
    let (attachments, mut attachment_points, render_bounds, mdat_notes) = render_meshes(&resource);
    for point in &mut attachment_points {
        point.bone_aligned = point.bone.as_deref().and_then(|bone| bone_aligned(root, bone));
    }
    notes.extend(mdat_notes);
    let (physics_bounds, physics_notes) = physics(&resource);
    notes.extend(physics_notes);

    let has_physics = resource.blocks_of(b"PHYS").next().is_some()
        || root
            .get("m_refPhysicsData")
            .and_then(Kv3Value::as_array)
            .is_some_and(|entries| !entries.is_empty());
    if !has_physics {
        notes.push(
            "no PHYS block and empty m_refPhysicsData: the model has no collision geometry \
             (fine for decorative prop_static, not for prop_physics)"
                .into(),
        );
    }

    Ok(ModelInfo {
        name: root.get_str("m_name").map(str::to_owned),
        hull,
        view,
        mass,
        surface_property,
        keyvalues_text,
        skins,
        bodygroups,
        sequences,
        attachments,
        attachment_points,
        has_physics: Some(has_physics),
        render_bounds,
        physics_bounds,
        bones: model_bones(root),
        blocks: resource.block_types(),
        notes,
    })
}

/// `m_modelSkeleton.m_boneName` with `m_nParent`.
fn model_bones(root: &Kv3Value) -> Vec<(String, i64)> {
    let Some(skeleton) = root.get("m_modelSkeleton") else { return Vec::new() };
    let (Some(names), Some(parents)) =
        (skeleton.get("m_boneName").and_then(Kv3Value::as_array), skeleton.get("m_nParent").and_then(Kv3Value::as_array))
    else {
        return Vec::new();
    };
    names
        .iter()
        .zip(parents)
        .filter_map(|(n, p)| Some((n.as_str()?.to_string(), p.as_i64().unwrap_or(-1))))
        .collect()
}

/// The `skin` choices: `m_materialGroups[].m_name`.
fn material_group_names(root: &Kv3Value) -> Vec<String> {
    root.get("m_materialGroups")
        .and_then(Kv3Value::as_array)
        .map(|groups| {
            groups
                .iter()
                .filter_map(|group| group.get_str("m_name"))
                .filter(|name| !name.is_empty())
                .map(str::to_owned)
                .collect()
        })
        .unwrap_or_default()
}

/// Bodygroups: `m_meshGroups` names plus the per-mesh masks that say which meshes belong to them.
fn body_groups(root: &Kv3Value) -> (Vec<BodyGroup>, Vec<String>) {
    let mut notes = Vec::new();
    let Some(names) = root.get("m_meshGroups").and_then(Kv3Value::as_array) else {
        return (Vec::new(), notes);
    };
    if names.is_empty() {
        return (Vec::new(), notes);
    }
    let masks: Vec<u64> = root
        .get("m_refMeshGroupMasks")
        .and_then(Kv3Value::as_array)
        .map(|masks| masks.iter().filter_map(Kv3Value::as_u64).collect())
        .unwrap_or_default();
    if names.len() > 64 {
        notes.push(format!(
            "{} mesh groups: only the first 64 fit the bodygroups mask",
            names.len()
        ));
    }
    let mut groups = Vec::with_capacity(names.len());
    for (index, name) in names.iter().enumerate() {
        let Some(value) = 1u64.checked_shl(index as u32) else {
            continue;
        };
        let name = name.as_str().unwrap_or_default();
        let (group, choice) = split_bodygroup_name(name);
        groups.push(BodyGroup {
            index: index as u32,
            name: name.to_owned(),
            value,
            mesh_count: masks.iter().filter(|mask| **mask & value != 0).count(),
            group,
            choice,
        });
    }
    (groups, notes)
}

/// Valve's exporter names a mesh group `"<group>_@<choice index>_#&<choice name>"` when both are
/// authored (`first_or_third_person_@2_#&firstperson_default`) and `"bg_@<index>"` when only the
/// group is known (the auto-generated spelling keeps its group, no choice). Splitting is a
/// convenience; the raw [`BodyGroup::name`] is always there too.
fn split_bodygroup_name(name: &str) -> (Option<String>, Option<String>) {
    let Some((head, tail)) = name.split_once("_@") else {
        return (None, None);
    };
    let group = (!head.is_empty()).then(|| head.to_owned());
    let (_, choice) = tail.split_once("_#&").unwrap_or((tail, ""));
    (group, (!choice.is_empty()).then(|| choice.to_owned()))
}

/// Sequence names from every `ASEQ` block: `m_localSequenceNameArray`, else the sequence
/// descriptors' `m_sName`.
fn sequences(resource: &Resource<'_>) -> (Vec<String>, Vec<String>) {
    let mut notes = Vec::new();
    let mut names: Vec<String> = Vec::new();
    let mut seen: std::collections::HashSet<String> = Default::default();
    let mut blocks = 0usize;
    for block in resource.blocks_of(b"ASEQ") {
        blocks += 1;
        let document = match kv3bin::decode(resource.block_bytes(block)) {
            Ok(document) => document,
            // The DATA block carries the model; a broken ASEQ only costs the sequences.
            Err(error) => {
                notes.push(format!(
                    "ASEQ block did not decode ({error}); sequences missing"
                ));
                continue;
            }
        };
        let root = &document.root;
        let mut from_names = false;
        if let Some(entries) = root
            .get("m_localSequenceNameArray")
            .and_then(Kv3Value::as_array)
        {
            for entry in entries.iter().filter_map(Kv3Value::as_str) {
                if !entry.is_empty() {
                    push_unique(&mut names, &mut seen, entry);
                    from_names = true;
                }
            }
        }
        if !from_names {
            if let Some(descriptors) = root
                .get("m_localS1SeqDescArray")
                .and_then(Kv3Value::as_array)
            {
                for name in descriptors
                    .iter()
                    .filter_map(|entry| entry.get_str("m_sName"))
                {
                    if !name.is_empty() {
                        push_unique(&mut names, &mut seen, name);
                    }
                }
            }
        }
    }
    if blocks == 0 {
        notes.push(
            "no ASEQ block: this model has no embedded sequences (a model that animates keeps them \
             in its own file, or in a separate .vseq)"
                .into(),
        );
    } else if names.is_empty() {
        notes.push(format!(
            "{blocks} ASEQ block(s) but no sequence names inside (m_localSequenceNameArray and \
             m_localS1SeqDescArray are empty)"
        ));
    }
    (names, notes)
}

/// Everything the `MDAT` render meshes carry: attachment names and their bounds.
#[allow(clippy::type_complexity)]
fn render_meshes(
    resource: &Resource<'_>,
) -> (Vec<String>, Vec<AttachmentPoint>, Option<Aabb>, Vec<String>) {
    let mut notes = Vec::new();
    let mut attachments: Vec<String> = Vec::new();
    let mut points: Vec<AttachmentPoint> = Vec::new();
    let mut attachment_seen: std::collections::HashSet<String> = Default::default();
    let mut bounds: Option<Aabb> = None;
    let mut blocks = 0usize;
    for block in resource.blocks_of(b"MDAT") {
        blocks += 1;
        let document = match kv3bin::decode(resource.block_bytes(block)) {
            Ok(document) => document,
            Err(error) => {
                notes.push(format!(
                    "MDAT block did not decode ({error}); its bounds/attachments are missing"
                ));
                continue;
            }
        };
        let root = &document.root;
        for attachment in root
            .get("m_attachments")
            .and_then(Kv3Value::as_array)
            .into_iter()
            .flatten()
        {
            let name = attachment
                .get("value")
                .and_then(|value| value.get_str("m_name"))
                .or_else(|| attachment.get_str("key"));
            if let Some(name) = name.filter(|name| !name.is_empty()) {
                if !attachment_seen.contains(name) {
                    let value = attachment.get("value");
                    points.push(AttachmentPoint {
                        name: name.to_string(),
                        bone: value
                            .and_then(|v| v.get("m_influenceNames"))
                            .and_then(Kv3Value::as_array)
                            .and_then(|a| a.first())
                            .and_then(Kv3Value::as_str)
                            .filter(|b| !b.is_empty())
                            .map(str::to_owned),
                        offset: value
                            .and_then(|v| v.get("m_vInfluenceOffsets"))
                            .and_then(Kv3Value::as_array)
                            .and_then(|a| a.first())
                            .and_then(Kv3Value::as_vec3),
                        influences: value
                            .and_then(|v| v.get("m_nInfluences"))
                            .and_then(Kv3Value::as_u64)
                            .map(|n| n as u32),
                        root_transform: value
                            .and_then(|v| v.get("m_bInfluenceRootTransform"))
                            .and_then(Kv3Value::as_array)
                            .and_then(|a| a.first())
                            .and_then(Kv3Value::as_bool)
                            .unwrap_or(false),
                        bone_aligned: None,
                    });
                }
                push_unique(&mut attachments, &mut attachment_seen, name);
            }
        }
        for scene in root
            .get("m_sceneObjects")
            .and_then(Kv3Value::as_array)
            .into_iter()
            .flatten()
        {
            if let Some((min, max)) = pair(scene, "m_vMinBounds", "m_vMaxBounds") {
                bounds = Some(grow(bounds, min, max));
            }
        }
    }
    if blocks == 0 {
        notes.push("no MDAT block: no render bounds and no attachments in the file".into());
    }
    (attachments, points, bounds, notes)
}

/// Physics presence/box from every `PHYS` block.
fn physics(resource: &Resource<'_>) -> (Option<Aabb>, Vec<String>) {
    let mut notes = Vec::new();
    let mut bounds: Option<Aabb> = None;
    for block in resource.blocks_of(b"PHYS") {
        let document = match kv3bin::decode(resource.block_bytes(block)) {
            Ok(document) => document,
            Err(error) => {
                notes.push(format!(
                    "PHYS block did not decode ({error}); the physics box is missing"
                ));
                continue;
            }
        };
        let mut shapes = 0usize;
        for part in document
            .root
            .get("m_parts")
            .and_then(Kv3Value::as_array)
            .into_iter()
            .flatten()
        {
            let Some(shape) = part.get("m_rnShape") else {
                continue;
            };
            // Convex hulls and single-collision meshes carry their own box.
            for hull in shape
                .get("m_hulls")
                .and_then(Kv3Value::as_array)
                .into_iter()
                .flatten()
            {
                let hull_bounds = hull.get("m_Hull").and_then(|hull| hull.get("m_Bounds"));
                if let Some((min, max)) =
                    hull_bounds.and_then(|b| pair(b, "m_vMinBounds", "m_vMaxBounds"))
                {
                    shapes += 1;
                    bounds = Some(grow(bounds, min, max));
                }
            }
            for mesh in shape
                .get("m_meshes")
                .and_then(Kv3Value::as_array)
                .into_iter()
                .flatten()
            {
                if let Some((min, max)) = mesh
                    .get("m_Mesh")
                    .and_then(|mesh| pair(mesh, "m_vMin", "m_vMax"))
                {
                    shapes += 1;
                    bounds = Some(grow(bounds, min, max));
                }
            }
            for sphere in shape
                .get("m_spheres")
                .and_then(Kv3Value::as_array)
                .into_iter()
                .flatten()
            {
                let sphere = sphere.get("m_Sphere");
                let center = sphere
                    .and_then(|sphere| sphere.get("m_vCenter"))
                    .and_then(Kv3Value::as_vec3);
                let radius = sphere
                    .and_then(|sphere| sphere.get("m_flRadius"))
                    .and_then(Kv3Value::as_f32);
                if let (Some(center), Some(radius)) = (center, radius) {
                    shapes += 1;
                    let min = [center[0] - radius, center[1] - radius, center[2] - radius];
                    let max = [center[0] + radius, center[1] + radius, center[2] + radius];
                    bounds = Some(grow(bounds, min, max));
                }
            }
        }
        if shapes == 0 {
            notes.push(
                "a PHYS block carries no hull/mesh/sphere box (its shapes are capsules, or the \
                 shape list is empty)"
                    .into(),
            );
        }
    }
    (bounds, notes)
}

/// A min/max key pair as a box; `None` when either end is missing.
fn pair(object: &Kv3Value, min_key: &str, max_key: &str) -> Option<Aabb> {
    Some((
        object.get(min_key)?.as_vec3()?,
        object.get(max_key)?.as_vec3()?,
    ))
}

/// `m_modelInfo.m_v*Min/Max` as a box; `None` when either end is missing or the box is all zero
/// (every compiled CS2 prop model writes zeros there).
fn box_pair(object: &Kv3Value, min_key: &str, max_key: &str) -> Option<Aabb> {
    let (min, max) = pair(object, min_key, max_key)?;
    if min.iter().all(|value| *value == 0.0) && max.iter().all(|value| *value == 0.0) {
        return None;
    }
    Some((min, max))
}

fn min_of(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[0].min(b[0]), a[1].min(b[1]), a[2].min(b[2])]
}

fn max_of(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[0].max(b[0]), a[1].max(b[1]), a[2].max(b[2])]
}

fn grow(bounds: Option<Aabb>, min: [f32; 3], max: [f32; 3]) -> Aabb {
    match bounds {
        Some(bounds) => (min_of(bounds.0, min), max_of(bounds.1, max)),
        None => (min, max),
    }
}

fn push_unique(names: &mut Vec<String>, seen: &mut std::collections::HashSet<String>, name: &str) {
    // The HashSet keeps the dedup O(1) per name: a hostile model repeating one name a million
    // times must not pay a quadratic scan.
    if seen.insert(name.to_owned()) {
        names.push(name.to_owned());
    }
}
