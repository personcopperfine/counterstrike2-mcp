#!/usr/bin/env python3
"""Build the installers around a package dir (crates/cs2-native/scripts/package.sh output) with
cargo-packager 0.11.8:

  appimage  cs2mcp-launcher as the AppImage's entry, the package at $APPDIR/opt/cs2mcp
  deb       /usr/bin/cs2mcp-launcher, the package at /opt/cs2mcp
  wix       the per-user MSI (wix/main.wxs), the package in %LOCALAPPDATA%\\Programs\\cs2-mcp
            (Windows only: WiX 3's candle/light)

  python3 -I packager.py --format appimage --package-dir <dir> --version 0.1.0 --out-dir <dir> [--verify]

The cargo-packager config is written per run into <out-dir>/.packager-<format>/ (its paths must
be absolute: the package dir differs between CI and a local run), with the WiX fragment for the
package tree next to it. `cargo packager` must be on PATH (cargo install cargo-packager --version
0.11.8 --locked). --verify (appimage): extract the result and check opt/cs2mcp against the
package's SHA256SUMS, so a tool that rewrote a file in there (linuxdeploy patches ELF files it
deploys) cannot go unnoticed.
"""
import argparse
import hashlib
import json
import os
import pathlib
import re
import subprocess
import sys
import uuid
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

HERE = pathlib.Path(__file__).resolve().parent
PRODUCT = "cs2-mcp"
IDENTIFIER = "io.github.personcopperfine.cs2mcp"
PUBLISHER = "cs2-mcp"
# stable across releases: MajorUpgrade finds the installed version through it
UPGRADE_NS = uuid.UUID("6a1f2d3e-5b7c-4e8f-9a0b-1c2d3e4f5a6b")


def wix_id(prefix, rel):
    return prefix + hashlib.sha1(rel.encode()).hexdigest()[:20]


def fragment(pkg: pathlib.Path) -> str:
    """One component per directory of the package, keyed on an HKCU value (per-user: ICE38),
    removing its directory on uninstall (ICE64). The launcher's File Id is LauncherExe."""
    regkey = f"Software\\{PUBLISHER}\\{PRODUCT}\\Files"
    comps = []

    def walk(d: pathlib.Path, rel: str, indent: str) -> str:
        out = []
        cid = wix_id("c_", rel or ".")
        guid = uuid.uuid5(UPGRADE_NS, "component:" + (rel or "."))
        out.append(f'{indent}<Component Id="{cid}" Guid="{{{str(guid).upper()}}}" Win64="yes">')
        out.append(f'{indent}  <RegistryValue Root="HKCU" Key={quoteattr(regkey)} Name={quoteattr(rel or ".")} Type="integer" Value="1" KeyPath="yes"/>')
        if rel:
            out.append(f'{indent}  <RemoveFolder Id="{wix_id("r_", rel)}" On="uninstall"/>')
        for f in sorted(p for p in d.iterdir() if p.is_file()):
            frel = f"{rel}/{f.name}" if rel else f.name
            fid = "LauncherExe" if frel == "cs2mcp-launcher.exe" else wix_id("f_", frel)
            out.append(f'{indent}  <File Id="{fid}" Source={quoteattr(str(f))} Name={quoteattr(f.name)}/>')
        out.append(f"{indent}</Component>")
        comps.append(cid)
        for sub in sorted(p for p in d.iterdir() if p.is_dir()):
            srel = f"{rel}/{sub.name}" if rel else sub.name
            out.append(f'{indent}<Directory Id="{wix_id("d_", srel)}" Name={quoteattr(sub.name)}>')
            out.append(walk(sub, srel, indent + "  "))
            out.append(f"{indent}</Directory>")
        return "\n".join(out)

    body = walk(pkg, "", "      ")
    refs = "\n".join(f'      <ComponentRef Id="{c}"/>' for c in comps)
    text = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- generated by crates/cs2-launcher/packaging/packager.py from {pkg} -->
<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">
  <Fragment>
    <DirectoryRef Id="INSTALLDIR">
{body}
    </DirectoryRef>
  </Fragment>
  <Fragment>
    <ComponentGroup Id="PackageFiles">
{refs}
    </ComponentGroup>
  </Fragment>
</Wix>
"""
    check_fragment(text)
    return text


def check_fragment(text):
    """The per-user rules, checked before WiX sees the fragment: unique ids, every component keyed
    on one HKCU value and no file, every directory removing itself, every component referenced."""
    w = "{http://schemas.microsoft.com/wix/2006/wi}"
    root = ET.fromstring(text.encode())
    ids = [e.get("Id") for e in root.iter() if e.get("Id") and not e.tag.endswith("Ref")]
    assert len(ids) == len(set(ids)) and all(len(i) <= 72 for i in ids), "fragment: ids"
    comps = list(root.iter(w + "Component"))
    for c in comps:
        kp = [e for e in c if e.get("KeyPath") == "yes"]
        assert len(kp) == 1 and kp[0].tag == w + "RegistryValue" and kp[0].get("Root") == "HKCU", c.get("Id")
    for d in root.iter(w + "Directory"):
        own = [c for c in d if c.tag == w + "Component"]
        assert len(own) == 1 and own[0].find(w + "RemoveFolder") is not None, d.get("Name")
    assert sorted(r.get("Id") for r in root.iter(w + "ComponentRef")) == sorted(c.get("Id") for c in comps)


def msi_version(v: str) -> str:
    """MSI: major.minor.patch, numbers only (a pre-release suffix is dropped)."""
    m = re.match(r"v?(\d+)\.(\d+)\.(\d+)", v)
    if not m:
        sys.exit(f"packager.py: version {v!r} is not x.y.z")
    return ".".join(m.groups())


def config(fmt, pkg: pathlib.Path, version, out: pathlib.Path, work: pathlib.Path):
    exe = "cs2mcp-launcher"
    c = {
        # set: cargo-packager 0.11.8 otherwise chdirs into the config *file* to guess it (ENOTDIR)
        "name": "cs2-launcher",
        "productName": PRODUCT,
        "version": msi_version(version) if fmt == "wix" else version.lstrip("v"),
        "identifier": IDENTIFIER,
        "publisher": PUBLISHER,
        "authors": ["cs2-mcp contributors"],
        "description": "Prepares your Steam Counter-Strike 2 install for the cs2-mcp MCP servers, launches it, and restores it afterwards",
        "homepage": "https://github.com/personcopperfine/counterstrike2-mcp",
        "category": "DeveloperTool",
        "outDir": str(out),
        "binariesDir": str(pkg),
        "binaries": [{"path": exe, "main": True}],
        "icons": [str(HERE / "icons" / "icon.png"), str(HERE / "icons" / "icon.ico")],
        "formats": [fmt],
    }
    if fmt == "appimage":
        c["appimage"] = {"files": {str(pkg): "opt/cs2mcp"}}
    elif fmt == "deb":
        c["deb"] = {"files": {str(pkg): "/opt/cs2mcp"}, "section": "games"}
    elif fmt == "wix":
        frag = work / "package-files.wxs"
        frag.write_text(fragment(pkg), encoding="utf-8")
        c["wix"] = {
            "template": str(HERE / "wix" / "main.wxs"),
            "fragmentPaths": [str(frag)],
            "componentGroupRefs": ["PackageFiles"],
        }
    return c


def sha256(p: pathlib.Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def verify_appimage(image: pathlib.Path, work: pathlib.Path):
    ex = work / "extract"
    if ex.exists():
        subprocess.run(["rm", "-rf", str(ex)], check=True)
    ex.mkdir(parents=True)
    # --appimage-extract needs no FUSE; it writes squashfs-root/ into the cwd
    subprocess.run([str(image), "--appimage-extract"], cwd=ex, check=True, stdout=subprocess.DEVNULL)
    root = ex / "squashfs-root"
    pkg = root / "opt" / "cs2mcp"
    sums = (pkg / "SHA256SUMS").read_text().splitlines()
    bad = []
    for line in sums:
        h, name = line.split(None, 1)
        name = name.lstrip("*").removeprefix("./")
        p = pkg / name
        if not p.is_file() or sha256(p) != h:
            bad.append(name)
    if bad:
        sys.exit(f"packager.py: the AppImage's opt/cs2mcp differs from SHA256SUMS: {bad}")
    print(f"packager.py: verified {len(sums)} files of opt/cs2mcp in {image.name} against SHA256SUMS")
    for need in ["AppRun", "usr/bin/cs2mcp-launcher"]:
        if not (root / need).exists():
            sys.exit(f"packager.py: {need} missing in the AppImage")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--format", required=True, choices=["appimage", "deb", "wix"])
    ap.add_argument("--package-dir", required=True, type=pathlib.Path)
    ap.add_argument("--version", required=True)
    ap.add_argument("--out-dir", required=True, type=pathlib.Path)
    ap.add_argument("--verify", action="store_true")
    a = ap.parse_args()
    pkg = a.package_dir.resolve()
    exe = "cs2mcp-launcher.exe" if a.format == "wix" else "cs2mcp-launcher"
    for need in [exe, "SHA256SUMS", "payload"]:
        if not (pkg / need).exists():
            sys.exit(f"packager.py: {pkg} has no {need} (scripts/package.sh output expected)")
    out = a.out_dir.resolve()
    work = out / f".packager-{a.format}"
    work.mkdir(parents=True, exist_ok=True)
    cfg = work / "packager.json"
    cfg.write_text(json.dumps(config(a.format, pkg, a.version, out, work), indent=2), encoding="utf-8")
    before = set(out.iterdir())
    subprocess.run(["cargo", "packager", "-c", str(cfg), "-f", a.format], check=True, env=dict(os.environ))
    made = sorted(p for p in set(out.iterdir()) - before if p.is_file())
    if not made:
        # a rerun overwrites the same name
        suffix = {"appimage": ".AppImage", "deb": ".deb", "wix": ".msi"}[a.format]
        made = sorted(p for p in out.iterdir() if p.name.endswith(suffix))
    for p in made:
        print(f"packager.py: {p}")
    if a.verify and a.format == "appimage":
        for p in made:
            if p.name.endswith(".AppImage"):
                verify_appimage(p, work)


main()
